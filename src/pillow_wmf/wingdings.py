def decode_wingdings(data):
    """Preserve one character per byte, including supplementary-plane symbols."""
    characters = []
    for byte in data:
        codepoint = _CODEPOINTS[byte - 32] if byte >= 32 else 0
        if not codepoint:
            raise UnsupportedOperation(f"No Unicode mapping for Wingdings byte 0x{byte:02X}")
        characters.append(chr(codepoint))
    return "".join(characters)
